def write_yaml(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")


def detect_and_repair_invalid_case(valid_payload: dict[str, Any]) -> dict[str, Any]:
    invalid_payload = dict(valid_payload)
    invalid_payload.pop("human_approval_required", None)
    invalid_payload.pop("tolerances", None)
    invalid_errors = validate_payload(invalid_payload, "build_packet.schema.json")

    write_json(INVALID_PAYLOAD_JSON_PATH, invalid_payload)
    write_yaml(INVALID_PAYLOAD_YAML_PATH, invalid_payload)

    repaired_payload = dict(invalid_payload)
    repaired_payload["tolerances"] = valid_payload["tolerances"]
    repaired_payload["human_approval_required"] = True
    repaired_errors = validate_payload(repaired_payload, "build_packet.schema.json")

    write_json(VALID_PAYLOAD_JSON_PATH, repaired_payload)
    write_yaml(VALID_PAYLOAD_YAML_PATH, repaired_payload)

    return {
        "invalid_payload": invalid_payload,
        "invalid_errors": invalid_errors,
        "repaired_payload": repaired_payload,
        "repaired_errors": repaired_errors,
    }


