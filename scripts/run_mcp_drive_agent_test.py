def run_command(command: list[str]) -> dict[str, Any]:
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
    return {
        "command": " ".join(command),
        "returncode": result.returncode,
        "status": "PASS" if result.returncode == 0 else "FAIL",
        "stdout": result.stdout.strip(),
        "stderr": result.stderr.strip(),
        "classification": classify_result(result.returncode, result.stderr),
    }


def classify_result(returncode: int, stderr: str) -> str:
    if returncode == 0:
        return "success"
    lower = stderr.lower()
    if "no module named" in lower or "not recognized" in lower:
        return "missing_dependency"
    if "permission" in lower or "access is denied" in lower:
        return "environment_limitation"
    return "code_failure"


